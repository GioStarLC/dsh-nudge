/**
 * Build the browser half from `src/` into the two files the module loader
 * ships: `client.js` (the plugin bundle) and `client.settings-jump.js` (the
 * package-local chunk it fetches on demand).
 *
 * The loader contract is the only thing this script knows about the shell:
 * a file is a call to `window.__ModuleLoader__.load({ id, factory(require) })`,
 * peer dependencies arrive through that `require`, and a chunk adds
 * `chunk: 'client.<name>.js'` and returns its exports. Rollup rewrites the ESM
 * imports into one CommonJS body; the envelope below hands that body the
 * loader's `require` and returns `module.exports`.
 *
 * Rollup is deliberate: it edits only the import/export statements, so every
 * other line keeps the bytes it has in `src/`. A template literal that carries
 * a `\n` still carries a newline after the build, and the artifact stays
 * readable next to its source. Tree shaking is off for the same reason — this
 * code is already one entry, and nothing should quietly disappear from it.
 *
 * `node scripts/build.mjs`          rewrite the artifacts
 * `node scripts/build.mjs --verify` build in memory and fail when the
 *                                   committed artifacts would change
 *
 * Verification is what `npm run check` runs first, so a source edit that was
 * not rebuilt fails before the tests do, and CI catches an artifact edited by
 * hand.
 */
import { rollup } from 'rollup'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const ROOT = new URL('..', import.meta.url)
const PACKAGE_ID = 'dsh-nudge'

/**
 * One artifact: the ESM entry, the file it becomes, and the extra loader fields.
 * The chunk name must match the file name and `client.<name>.js`, because the
 * loader resolves a fetch by that name.
 */
const TARGETS = [
  {
    source: 'src/client/index.js',
    output: 'client.js',
  },
  {
    source: 'src/client.settings-jump.js',
    output: 'client.settings-jump.js',
    chunk: 'client.settings-jump.js',
  },
]

const HEADER = (target) => `/**
 * Generated by scripts/build.mjs from ${target.source} — do not edit this file.
 * Rebuild: npm run build
 */
`

/**
 * Wrap one rollup bundle in the `__ModuleLoader__.load` envelope.
 *
 * The bundle body resolves `require` lexically to the factory parameter, which
 * is how rollup's `require('react')` reaches the shell's loader. `module` and
 * `exports` are the CommonJS pair the CJS output writes to.
 */
function envelope(code, target) {
  const chunk = target.chunk === undefined ? '' : `\n  chunk: '${target.chunk}',`
  return `${HEADER(target)}window.__ModuleLoader__.load({
  id: '${PACKAGE_ID}',${chunk}
  factory(require) {
    const module = { exports: {} }
    const exports = module.exports
${code.trimEnd()}
    return module.exports
  },
})
`
}

/**
 * Compile one target in memory: no writes until every target has built, so a
 * failed build cannot leave one fresh artifact and one stale.
 */
async function compile(target) {
  const bundle = await rollup({
    input: fileURLToPath(new URL(target.source, ROOT)),
    // React is the shell's, not ours: the loader supplies it.
    external: ['react'],
    // Nothing in this code is dead, and a function reached only through a
    // render or a callback must not be shaken out.
    treeshake: false,
    onwarn(warning, warn) {
      // An import typo must not silently become a runtime `require`.
      if (warning.code === 'UNRESOLVED_IMPORT') {
        throw new Error(`build: unresolved import in ${target.source}: ${warning.message}`)
      }
      // Modules are layers, not a web: a cycle means two files own one seam.
      if (warning.code === 'CIRCULAR_DEPENDENCY') {
        throw new Error(`build: circular dependency: ${warning.message}`)
      }
      warn(warning)
    },
  })
  try {
    const { output } = await bundle.generate({
      format: 'cjs',
      exports: 'named',
      // Keep the source's own `const`/`let` spelling.
      generatedCode: { constBindings: true },
    })
    return envelope(output[0].code, target)
  } finally {
    await bundle.close()
  }
}

/** Read one artifact, or undefined when it has never been built. */
async function readOutput(name) {
  try {
    return await readFile(new URL(name, ROOT), 'utf8')
  } catch (error) {
    if (error?.code === 'ENOENT') return undefined
    throw error
  }
}

/** First line where two strings differ, for the failure message. */
function firstDifference(built, shipped) {
  const left = built.split('\n')
  const right = shipped.split('\n')
  for (let index = 0; index < Math.max(left.length, right.length); index += 1) {
    if (left[index] !== right[index]) return index + 1
  }
  return 0
}

const verify = process.argv.includes('--verify')
const built = []
for (const target of TARGETS) built.push({ target, code: await compile(target) })

if (verify) {
  let changed = 0
  for (const { target, code } of built) {
    const shipped = await readOutput(target.output)
    if (shipped === code) continue
    changed += 1
    const line = shipped === undefined ? 0 : firstDifference(code, shipped)
    console.error(
      `build: ${target.output} is ${shipped === undefined ? 'missing' : `stale (first difference at line ${line})`}`,
    )
  }
  if (changed > 0) {
    console.error('build: run `npm run build` and commit the artifacts')
    process.exit(1)
  }
  console.log(`build: ${TARGETS.map((target) => target.output).join(', ')} match src/`)
} else {
  for (const { target, code } of built) {
    const shipped = await readOutput(target.output)
    if (shipped === code) {
      console.log(`build: ${target.output} unchanged`)
      continue
    }
    await writeFile(new URL(target.output, ROOT), code)
    console.log(`build: wrote ${target.output}`)
  }
}
